import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import type { Evidence } from './harness.ts';

const names = ['a-hold-tx', 'b-leak', 'c-cpu-block', 'd-retry-storm'];
for (const n of names) {
  const r = spawnSync(process.execPath, ['--import', 'tsx', `scripts/incident/${n}.ts`], { stdio: 'inherit' });
  if (r.status !== 0) process.exit(r.status ?? 1);
}
const ev: Evidence[] = names.map((n) => JSON.parse(readFileSync(`evidence/${n}.json`, 'utf8')));
const rows = [
  ['Timeouts (pool + query)', (e: Evidence) => e.outcomes.poolTimeouts + e.outcomes.queryTimeouts],
  ['Pool peak waiting', (e: Evidence) => e.pool.peakWaiting],
  ['Recovered without restart', (e: Evidence) => (e.recovered ? 'yes' : 'NO')],
  ['Peak idle in transaction', (e: Evidence) => e.pgStatActivity.peakIdleInTransaction],
  ['Peak lock waits', (e: Evidence) => e.pgStatActivity.peakLockWaits],
  ['Oldest transaction (ms)', (e: Evidence) => e.pgStatActivity.oldestXactMs],
  ['Event loop p99 (ms)', (e: Evidence) => e.eventLoop.p99ms],
  ['Heartbeats late', (e: Evidence) => `${e.eventLoop.heartbeatsLate}/${e.eventLoop.heartbeatsTotal}`],
  ['Attempts per job', (e: Evidence) => e.outcomes.retryAmplification],
  ['Paid submissions per job', (e: Evidence) => e.outcomes.paidPerJob],
] as const;
const md = [
  '# Incident evidence',
  '',
  'Generated by `npm run incident`. Pool max 5, Postgres 16. Numbers vary a little per run; the pattern does not.',
  '',
  `| Signal | ${names.join(' | ')} |`,
  `| --- | ${names.map(() => '---').join(' | ')} |`,
  ...rows.map(([label, f]) => `| ${label} | ${ev.map((e) => f(e)).join(' | ')} |`),
  '',
].join('\n');
writeFileSync('evidence/SUMMARY.md', md);
console.log('\n' + md);
